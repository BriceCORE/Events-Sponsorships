import assert from 'node:assert/strict';
import {validDate, addDays, formatDate, overlapsDates, isCritical, monthDays, moveMonth} from './event-dates.ts';

assert.equal(validDate('2026-02-29'), false);
assert.equal(validDate('2028-02-29'), true);
assert.equal(validDate('2026-2-03'), false);
assert.equal(addDays('2026-03-07', 2), '2026-03-09');
assert.equal(addDays('2026-10-31', 2), '2026-11-02');
assert.equal(addDays('2026-12-31', 1), '2027-01-01');
assert.equal(formatDate('2026-09-23'), 'Sep 23, 2026');
const event = (startDate, endDate = '', decision = 'attend') => ({startDate, endDate, decision});
assert.equal(isCritical(event('2026-09-23'), '2026-09-23'), true);
assert.equal(isCritical(event('2026-10-20'), '2026-09-23'), true);
assert.equal(isCritical(event('2026-10-21'), '2026-09-23'), false);
assert.equal(isCritical(event('2026-09-20', '2026-09-23'), '2026-09-23'), true);
assert.equal(isCritical(event('2026-09-22'), '2026-09-23'), false);
assert.equal(isCritical(event('2026-09-24', '', 'decline'), '2026-09-23'), false);
assert.equal(isCritical(event(''), '2026-09-23'), false);
assert.equal(overlapsDates(event('2026-09-28', '2026-10-02'), '2026-10-01', '2026-10-31'), true);
assert.equal(overlapsDates(event(''), '2026-10-01', ''), false);
assert.equal(overlapsDates(event(''), '', ''), true);
assert.equal(moveMonth('2026-12', 1), '2027-01');
const september = monthDays('2026-09');
assert.equal(september.length, 42);
assert.equal(september[0], '2026-08-30');
assert.equal(september[2], '2026-09-01');
assert.equal(september[41], '2026-10-10');
console.log('PASS 22 calendar-date checks, including DST, four-week limits, ongoing events, and weekday alignment.');
